const std::uint8_t* GlyphRows(char32_t code_point) {
  constexpr char32_t kFirstGlyph = U' ';
  constexpr char32_t kLastGlyph = U'~';
  if (code_point >= kFirstGlyph && code_point <= kLastGlyph) {
    return kGlyphs[static_cast<std::size_t>(code_point - kFirstGlyph)];
  }
  // Non-ASCII, control and out-of-range code points all paint '?'.
  return kGlyphs[static_cast<std::size_t>(U'?' - kFirstGlyph)];
}

std::size_t DecodeUtf8(std::string_view text, std::size_t offset, char32_t* code_point) {
  const auto lead = static_cast<unsigned char>(text[offset]);
  const std::size_t length = SequenceLength(lead);
  bool valid = length != 0;
  if (valid && length > 1) {
    valid = offset + length <= text.size();
    for (std::size_t index = 1; valid && index < length; ++index) {
      valid = IsContinuationByte(static_cast<unsigned char>(text[offset + index]));
    }
  }
  if (!valid) {
    *code_point = static_cast<char32_t>(0xFFFD);
    return 1;
  }
  if (length == 1) {
    *code_point = static_cast<char32_t>(lead);
    return 1;
  }
  std::uint32_t value = 0;
  if (length == 2) {
    value = static_cast<std::uint32_t>(lead & 0x1Fu);
  } else if (length == 3) {
    value = static_cast<std::uint32_t>(lead & 0x0Fu);
  } else {
    value = static_cast<std::uint32_t>(lead & 0x07u);
  }
  for (std::size_t index = 1; index < length; ++index) {
    value = (value << 6) |
            static_cast<std::uint32_t>(static_cast<unsigned char>(text[offset + index]) & 0x3Fu);
  }
  *code_point = static_cast<char32_t>(value);
  return length;
}

